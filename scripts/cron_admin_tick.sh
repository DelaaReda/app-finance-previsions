export FC_ADMIN_PROMPT_TIMEOUT_SECONDS="${FC_ADMIN_PROMPT_TIMEOUT_SECONDS:-360}"
export FC_ADMIN_RETRY_TIMEOUT_SECONDS="${FC_ADMIN_RETRY_TIMEOUT_SECONDS:-150}"
export FC_ADMIN_TICK_TIMEOUT_SECONDS="${FC_ADMIN_TICK_TIMEOUT_SECONDS:-540}"
